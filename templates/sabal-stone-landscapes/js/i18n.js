const EN = {};
let current = 'en';
const listeners = [];

function capture() {
  document.querySelectorAll('[data-i18n]').forEach(el => { const k = el.dataset.i18n; if (!(k in EN)) EN[k] = el.textContent; });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { const k = el.dataset.i18nHtml; if (!(k in EN)) EN[k] = el.innerHTML; });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => el.dataset.i18nAttr.split(',').forEach(pair => {
    const [attr, k] = pair.split(':'); if (!(k in EN)) EN[k] = el.getAttribute(attr) || '';
  }));
  EN['nav.close'] = DYN.en.close;
}

export function t(k) { return (current === 'es' ? ES[k] : EN[k]) ?? EN[k] ?? ''; }
export function dyn(k) { return DYN[current][k]; }
export function lang() { return current; }
export function onLang(fn) { listeners.push(fn); }

export function setLang(l, save = true) {
  current = l === 'es' ? 'es' : 'en';
  const D = current === 'es' ? ES : EN;
  document.querySelectorAll('[data-i18n]').forEach(el => { const v = D[el.dataset.i18n] ?? EN[el.dataset.i18n]; if (v != null && el.textContent !== v) el.textContent = v; });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { const v = D[el.dataset.i18nHtml] ?? EN[el.dataset.i18nHtml]; if (v != null && el.innerHTML !== v) el.innerHTML = v; });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => el.dataset.i18nAttr.split(',').forEach(pair => {
    const [attr, k] = pair.split(':'); const v = D[k] ?? EN[k]; if (v != null) el.setAttribute(attr, v);
  }));
  document.documentElement.lang = current;
  document.title = D['meta.title'] ?? EN['meta.title'];
  document.querySelectorAll('.lang__b').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === current)));
  if (save) { try { localStorage.setItem('ss-lang', current); } catch (e) { /* private mode */ } }
  listeners.forEach(fn => fn(current));
}

export function initI18n() {
  capture();
  let saved = 'en';
  try { saved = localStorage.getItem('ss-lang') || 'en'; } catch (e) { /* ignore */ }
  document.querySelectorAll('.lang__b').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang)));
  if (saved === 'es') setLang('es', false);
  else document.documentElement.lang = 'en';
}
