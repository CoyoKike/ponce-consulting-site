const EN = {};
let current = 'en';
const listeners = [];

function harvest() {
  document.querySelectorAll('[data-i18n]').forEach(el => { const k = el.dataset.i18n; if (!(k in EN)) EN[k] = el.textContent; });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { const k = el.dataset.i18nHtml; if (!(k in EN)) EN[k] = el.innerHTML; });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => el.dataset.i18nAttr.split(',').forEach(pair => {
    const [attr, k] = pair.split(':'); if (!(k in EN)) EN[k] = el.getAttribute(attr) || '';
  }));
}

export function apply(lang) {
  current = lang === 'es' ? 'es' : 'en';
  const D = current === 'es' ? ES : EN;
  const t = k => (k in D ? D[k] : EN[k]);
  document.documentElement.lang = current;
  document.querySelectorAll('[data-i18n]').forEach(el => { const v = t(el.dataset.i18n); if (v != null) el.textContent = v; });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { const v = t(el.dataset.i18nHtml); if (v != null) el.innerHTML = v; });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => el.dataset.i18nAttr.split(',').forEach(pair => {
    const [attr, k] = pair.split(':'); const v = t(k); if (v != null) el.setAttribute(attr, v);
  }));
  document.querySelectorAll('.lang__b').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === current)));
  try { localStorage.setItem('keelson-lang', current); } catch (e) { /* private mode: the choice just isn't remembered */ }
  listeners.forEach(f => f(current));
}

export const lang = () => current;
export const dyn = () => DYN[current];
export const onLang = f => listeners.push(f);

export function initI18n() {
  harvest();
  let saved = 'en';
  try { saved = localStorage.getItem('keelson-lang') || 'en'; } catch (e) { saved = 'en'; }
  document.querySelectorAll('.lang__b').forEach(b => b.addEventListener('click', () => apply(b.dataset.lang)));
  apply(saved);
}
